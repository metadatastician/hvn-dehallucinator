# to_agda.sh <traces> <out.agda>
#
# One Agda module whose lemmas say: running EngineCore.step along this command
# sequence from the model's start state gives exactly the (state, exit) list the
# engine produced. The proof kernel evaluates the model; `refl` accepts a lemma
# only if the model and the recorded engine behaviour agree on every step.
set -euo pipefail
traces="$1"; out="$2"
status() { case "$1" in RUNNING) echo running;; COMPLETE) echo complete;;
           EMERGENCY_STOP) echo emergency-stop;; *) echo "NO-SUCH-STATUS-$1";; esac; }
exitc()  { case "$1" in 0) echo ok;; 1) echo refused;; 3) echo tripped;;
           4) echo unmeasured;; *) echo "NO-SUCH-EXIT-$1";; esac; }
cmd()    { case "$1" in
  i[0-9]*) echo "init ${1#i}";; f[0-9]*) echo "init-from (counted ${1#f})";;
  ff) echo "init-from failed";; at) echo attempt;; u[0-9]*) echo "update (counted ${1#u})";;
  uf) echo "update failed";; v[0-9]*) echo verify;; st) echo show;;
  *) echo "NO-SUCH-TOKEN-$1";; esac; }
{
  echo '{-# OPTIONS --safe --without-K #-}'
  echo '-- Generated by tests/difftest/to_agda.sh; not committed.'
  echo 'module Diff where'
  echo 'open import ResidualEvidence.Prelude using (_≡_; refl; _,_; fst; Nat)'
  echo 'open import Agda.Builtin.List using (List; []; _∷_)'
  echo 'open import Fibre using (TaskState; task; running; complete; emergency-stop)'
  echo 'open import EngineCore using (Command; init; init-from; attempt; update; verify; show; Reading; counted; failed; Exit; ok; refused; tripped; unmeasured; step)'
  echo 'open import Agda.Builtin.Sigma using (Σ)'
  echo 'run : List Command → TaskState → List (Σ TaskState (λ _ → Exit))'
  echo 'run []       s = []'
  echo 'run (c ∷ cs) s = step c s ∷ run cs (fst (step c s))'
  k=0
  while IFS='|' read -r toks obs; do
    k=$((k + 1)); cs=""; es=""
    for t in $toks; do cs+="($(cmd "$t")) ∷ "; done
    IFS=';' read -ra recs <<< "$obs"
    for r in "${recs[@]}"; do
      IFS=, read -r rc tot comp att st <<< "$r"
      es+="(task $tot $comp $att $(status "$st") , $(exitc "$rc")) ∷ "
    done
    echo "t$k : run (${cs}[]) (task 0 0 0 running) ≡ (${es}[])"
    echo "t$k = refl"
  done < "$traces"
} > "$out"
