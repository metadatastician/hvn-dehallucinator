# to_tla.sh <traces> <out-dir>
#
# Writes <out-dir>/Traces.tla (the engine's recorded traces as TLA+ data) and
# <out-dir>/lens.txt (trace id and length). tests/difftest/TraceCheck.tla then
# lets TLC replay each trace against Engine.tla's own actions.
#
# A record is <<class, total, completed, attempts, status, rem, arg>>: `class`
# names the Engine.tla action that must take the step, `rem` the count the
# verifier reported (99: none), `arg` the total given to `init` (99: none) and
# the observables are what the engine wrote.
set -euo pipefail
traces="$1"; dir="$2"; mkdir -p "$dir"
cls() { case "$1" in
  i[0-9]*) echo "\"init\",99,${1#i}";; f[0-9]*) echo "\"initfrom\",${1#f},99";; ff) echo '"ro",99,99';;
  at) echo '"attempt",99,99';; u[0-9]*) echo "\"updm\",${1#u},99";; uf) echo '"updf",99,99';;
  v[0-9]*) echo "\"ro\",${1#v},99";; st) echo '"ro",99,99';; *) echo "\"BAD-$1\",99,99";; esac; }
{
  echo '---- MODULE Traces ----'
  echo '(* Generated by tests/difftest/to_tla.sh; not committed. *)'
  echo 'EXTENDS Naturals, Sequences'
  echo 'Tr == <<'
  k=0; : > "$dir/lens.txt"
  while IFS='|' read -r toks obs; do
    k=$((k + 1)); [ "$k" -gt 1 ] && echo ','
    IFS=' ' read -ra tk <<< "$toks"; IFS=';' read -ra recs <<< "$obs"
    printf '  <<'
    for i in "${!tk[@]}"; do
      [ "$i" -gt 0 ] && printf ', '
      IFS=, read -r rc tot comp att st <<< "${recs[$i]}"
      IFS=, read -r c rem arg <<< "$(cls "${tk[$i]}")"
      # a command refused by a stopped engine (exit 1) is a stutter in Engine.tla
      case "${tk[$i]}:$rc" in at:1|u*:1) c='"refused"'; rem=99 ;; esac
      printf '<<%s, %s, %s, %s, "%s", %s, %s>>' "$c" "$tot" "$comp" "$att" "$st" "$rem" "$arg"
    done
    printf '>>'
    echo "$k ${#tk[@]}" >> "$dir/lens.txt"
  done < "$traces"
  echo
  echo '>>'
  echo '===='
} > "$dir/Traces.tla"
