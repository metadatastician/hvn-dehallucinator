# emit-table.sh > tests/crosscheck/explorer-table.txt
#
# Prints the explorer table: for each of the certified finite checker's 546
# configurations, in `allConfigs` order, the presence verdict, the identity
# status and every candidate world the checker enumerates. It uses Lean's
# compiled evaluator over the Lean leg's restatement. The output is data, not
# evidence. What makes it evidence is tests/crosscheck/check.sh, where each
# kernel recomputes the table and must equal it:
#   * Agda, with residual-evidence-types' own Finite.Checker, at the pin;
#   * Rocq and Lean, with their restatements of it.
# A table emitted from a wrong restatement fails the Agda check.
#
# Line format: <residual> <noiseBound> <view> <any|zero> | <verdict> <id-status> | <latent>,<noise> ...
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.."
lean="${LEAN:-lean}"
src=verification/proofs/lean4/Haruspex.lean
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
end="$(grep -n '^end Haruspex$' "$src" | cut -d: -f1)"
{
  head -n $((end - 1)) "$src"
  cat <<'EOF'
def zs : ZInt → String
  | .pos n    => toString n
  | .negsuc n => "-" ++ toString (n + 1)
def verdictS : Verdict → String
  | .entailed => "entailed" | .refuted => "refuted"
  | .unresolved => "unresolved" | .inconsistent => "inconsistent"
def idS : IdStatus → String
  | .identified => "identified" | .unidentified => "unidentified" | .no_candidate => "no-candidate"
def viewS : View → String
  | .exact => "exact" | .sign => "sign" | .magnitude => "magnitude"
def tableLine (cfg : Config) : String :=
  zs cfg.residual ++ " " ++ toString cfg.noiseBound ++ " " ++ viewS cfg.view ++ " " ++
  (if cfg.assumeZero then "zero" else "any") ++ " | " ++
  verdictS (presenceC cfg) ++ " " ++ idS (identityC cfg) ++ " |" ++
  String.join ((enumerate cfg).map (fun w => " " ++ zs w.1 ++ "," ++ zs w.2))
#eval IO.println (String.intercalate "\n" (allConfigs.map tableLine))
end Haruspex
EOF
} > "$work/Emit.lean"
echo "# SPDX-License-Identifier: MPL-2.0"
echo "# Generated by tests/crosscheck/emit-table.sh; checked by tests/crosscheck/check.sh."
echo "# <residual> <noiseBound> <view> <any|zero> | <verdict> <id-status> | <latent>,<noise> ..."
(cd "$work" && "$lean" Emit.lean)
